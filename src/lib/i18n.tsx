/** English names that come from the database (e.g. places added by the admin). Existing entries win. */
export function addTranslations(map: Record<string, string>) {
  for (const [k, v] of Object.entries(map)) if (!(k in EN)) EN[k] = v;
}

export function t(s: string, vars?: Record<string, string | number>): string {
  let out = currentLang === "en" ? (EN[s] ?? s) : s;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
  }
  return out;
}

const LangCtx = createContext<{ lang: Lang; setLang: (l: Lang) => void; dir: "rtl" | "ltr" }>({ lang: "ar", setLang: () => {}, dir: "rtl" });
export const useLang = () => useContext(LangCtx);

const STORAGE_KEY = "va-lang";

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ar");
  // Set during render (not in an effect) so t() returns the new language in this same render pass.
  currentLang = lang;

  // Persist only on an explicit switch: writing from an effect could overwrite the saved choice before it is restored.
  const setLang = (next: Lang) => {
    currentLang = next;
    setLangState(next);
    try { localStorage.setItem(STORAGE_KEY, next); } catch { /* ignore */ }
  };

  useEffect(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved === "en" || saved === "ar") setLangState(saved);
    } catch { /* ignore */ }
  }, []);

  useEffect(() => {
    const html = document.documentElement;
    html.lang = lang;
    html.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);

  return <LangCtx.Provider value={{ lang, setLang, dir: lang === "ar" ? "rtl" : "ltr" }}>{children}</LangCtx.Provider>;
}
