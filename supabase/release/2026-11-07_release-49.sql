begin;
-- Every unit has a public code, and a WhatsApp question about it reaches the unit's owner.
-- * project_units.unit_no (VP-12) and compound_units.unit_no (VC-12): numbers the site shows next to each unit and
--   puts in the WhatsApp message; fixed once given (nobody sets or changes them from the app).
-- * wa_conversations.owner_unit_kind / owner_unit_id: the project or compound unit a chat is about.
-- * wa_assign_unit (service role): the bot hands a chat about a project / compound unit to its developer and rings
--   their bell, like wa_assign_owner does for listings.
-- * wa_assign_owner: a mall unit without its own broker goes to the mall's developer.
-- * wa_owner_threads shows the unit; wa_release_owner clears it.
-- Additive only; re-runnable.

alter table public.project_units add column if not exists unit_no bigint generated by default as identity;
create unique index if not exists project_units_unit_no on public.project_units (unit_no);
alter table public.compound_units add column if not exists unit_no bigint generated by default as identity;
create unique index if not exists compound_units_unit_no on public.compound_units (unit_no);

-- The number comes from the sequence only: an insert from the app can't pick one, an update can't change it.
create or replace function public.units_keep_no()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'UPDATE' then
    new.unit_no := old.unit_no;
  elsif coalesce(auth.role(), '') <> 'service_role' then
    new.unit_no := nextval(pg_get_serial_sequence(tg_table_schema || '.' || tg_table_name, 'unit_no'));
  end if;
  return new;
end $$;
revoke execute on function public.units_keep_no() from public, anon, authenticated;
drop trigger if exists project_units_keep_no on public.project_units;
create trigger project_units_keep_no before insert or update on public.project_units for each row execute function public.units_keep_no();
drop trigger if exists compound_units_keep_no on public.compound_units;
create trigger compound_units_keep_no before insert or update on public.compound_units for each row execute function public.units_keep_no();

alter table public.wa_conversations add column if not exists owner_unit_kind text check (owner_unit_kind is null or owner_unit_kind in ('project', 'compound'));
alter table public.wa_conversations add column if not exists owner_unit_id uuid;

-- A listing's owner: its broker, or for a mall unit without one, the mall's developer.
create or replace function public.wa_assign_owner(_phone text, _property uuid)
returns uuid language plpgsql security definer set search_path = public as $$
declare b uuid; code bigint; title text; who text;
begin
  select coalesce(br.id, md.id), p.listing_no, p.title into b, code, title
  from public.properties p
  left join public.brokers br on br.id = p.broker_id and br.is_active and br.suspended_at is null
  left join public.malls m on m.id = p.mall_id and p.category = 'mall'
  left join public.brokers md on md.id = m.developer_id and md.is_active and md.suspended_at is null
  where p.id = _property and p.review_status = 'approved';
  if b is null then return null; end if;
  select coalesce(c.name, 'عميل') into who from public.wa_conversations c where c.phone = _phone;
  if not found then return null; end if;
  update public.wa_conversations set owner_broker_id = b, owner_property_id = _property, owner_unit_kind = null, owner_unit_id = null,
    owner_assigned_at = now(), owner_replied_at = null, owner_alerted_at = null, owner_unread = 1
  where phone = _phone;
  update public.wa_messages set broker_id = b where phone = _phone and broker_id is null and created_at > now() - interval '1 hour';
  perform public.notify_company(b, 'new_message', 'عميل بيسأل على إعلانك على الواتساب',
    who || ' سأل على ' || coalesce('VA-' || code, title, 'إعلانك') || ' — رد عليه من «محادثات الواتساب».', null, '/dashboard?tab=wa');
  return b;
end $$;
revoke execute on function public.wa_assign_owner(text, uuid) from public, anon, authenticated;
grant execute on function public.wa_assign_owner(text, uuid) to service_role;

-- A project unit (VP-n) goes to the project's developer, a compound unit (VC-n) to the compound's developer.
-- Units of a compound run by Value Aqar (no developer account) stay with the team: returns null.
create or replace function public.wa_assign_unit(_phone text, _kind text, _no bigint)
returns uuid language plpgsql security definer set search_path = public as $$
declare b uuid; uid uuid; what text; who text;
begin
  if _kind = 'project' then
    select pr.developer_id, u.id, 'VP-' || u.unit_no || ' (' || u.unit_type || ' في ' || pr.name || ')' into b, uid, what
    from public.project_units u join public.projects pr on pr.id = u.project_id and pr.review_status = 'approved'
    join public.brokers d on d.id = pr.developer_id and d.is_active and d.suspended_at is null
    where u.unit_no = _no;
  elsif _kind = 'compound' then
    select c.developer_id, u.id, 'VC-' || u.unit_no || ' (' || u.unit_type || ' في ' || c.name || ')' into b, uid, what
    from public.compound_units u join public.compounds c on c.id = u.compound_id and c.is_active
    join public.brokers d on d.id = c.developer_id and d.is_active and d.suspended_at is null
    where u.unit_no = _no;
  end if;
  if b is null then return null; end if;
  select coalesce(c.name, 'عميل') into who from public.wa_conversations c where c.phone = _phone;
  if not found then return null; end if;
  update public.wa_conversations set owner_broker_id = b, owner_property_id = null, owner_unit_kind = _kind, owner_unit_id = uid,
    owner_assigned_at = now(), owner_replied_at = null, owner_alerted_at = null, owner_unread = 1
  where phone = _phone;
  update public.wa_messages set broker_id = b where phone = _phone and broker_id is null and created_at > now() - interval '1 hour';
  perform public.notify_company(b, 'new_message', 'عميل بيسأل على وحدة عندك على الواتساب',
    who || ' سأل على ' || what || ' — رد عليه من «محادثات الواتساب».', null, '/dashboard?tab=wa');
  return b;
end $$;
revoke execute on function public.wa_assign_unit(text, text, bigint) from public, anon, authenticated;
grant execute on function public.wa_assign_unit(text, text, bigint) to service_role;

-- Same columns as before; a chat about a project / compound unit shows the unit in property_title.
create or replace function public.wa_owner_threads()
returns table (id uuid, name text, phone_tail text, property_id uuid, property_code bigint, property_title text,
  last_message text, last_at timestamptz, unread integer, is_current boolean, can_reply boolean)
language sql stable security definer set search_path = public as $$
  with me as (select public.current_broker_id() as b)
  select c.id, c.name, right(c.phone, 3),
    case when c.owner_broker_id = me.b then c.owner_property_id end,
    case when c.owner_broker_id = me.b then p.listing_no end,
    case when c.owner_broker_id = me.b then coalesce(p.title, un.label) end,
    m.body, m.created_at,
    case when c.owner_broker_id = me.b then c.owner_unread else 0 end,
    c.owner_broker_id = me.b,
    c.owner_broker_id = me.b and c.last_inbound_at > now() - interval '24 hours'
  from me
  join public.wa_conversations c on me.b is not null
  join lateral (select x.body, x.created_at from public.wa_messages x where x.phone = c.phone and x.broker_id = me.b
    order by x.created_at desc limit 1) m on true
  left join public.properties p on p.id = c.owner_property_id
  left join lateral (
    select 'VP-' || u.unit_no || ' · ' || u.unit_type || ' — ' || pr.name as label
    from public.project_units u join public.projects pr on pr.id = u.project_id
    where c.owner_unit_kind = 'project' and u.id = c.owner_unit_id
    union all
    select 'VC-' || u.unit_no || ' · ' || u.unit_type || ' — ' || cp.name
    from public.compound_units u join public.compounds cp on cp.id = u.compound_id
    where c.owner_unit_kind = 'compound' and u.id = c.owner_unit_id
    limit 1) un on true
  order by m.created_at desc
  limit 200
$$;
revoke execute on function public.wa_owner_threads() from public, anon;
grant execute on function public.wa_owner_threads() to authenticated;

create or replace function public.wa_release_owner(_phone text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.staff_can('wa_inbox', 'edit') then raise exception 'not allowed' using errcode = '42501'; end if;
  update public.wa_conversations set owner_broker_id = null, owner_property_id = null, owner_unit_kind = null, owner_unit_id = null,
    owner_assigned_at = null, owner_replied_at = null, owner_alerted_at = null, owner_unread = 0
  where phone = _phone;
end $$;
revoke execute on function public.wa_release_owner(text) from public, anon;
grant execute on function public.wa_release_owner(text) to authenticated;
commit;
